from ...utils import rest
from starkcore.utils.api import from_api_json
from starkcore.utils.resource import Resource
from starkcore.utils.checks import check_datetime, check_date
from ..__fixedinvestment import _resource as _fixed_investment_resource


class Log(Resource):
    """# fixedinvestment.Log object
    Every time a FixedInvestment entity is modified, a corresponding fixedinvestment.Log
    is generated for the entity. This log is never generated by the
    user, but it can be retrieved to check additional information
    on the FixedInvestment.
    In withdrawal logs: transaction_amount = withdrawn_invested_amount + yield_amount - taxes.
    ## Attributes (return-only):
    - id [string]: unique id returned when the log is created. ex: "5656565656565656"
    - investment [FixedInvestment]: FixedInvestment entity to which the log refers to, as it was at that point.
    - type [string]: type of the FixedInvestment event which triggered the log creation. ex: "withdrawing" or "withdrawn"
    - description [string]: human readable description of what happened. ex: "Withdraw confirmed in the amount of R$ 2.095,20."
    - errors [list of strings]: list of errors linked to this FixedInvestment event
    - taxes [list of dictionaries]: taxes charged in this step, with type and amount. ex: [{"type": "ir", "amount": 810}]
    - transaction_id [string]: ledger transaction id tied to this step. ex: "4630817543012352"
    - transaction_amount [integer]: amount of the ledger transaction tied to this step, in cents. ex: 209520 (= R$ 2,095.20)
    - withdrawn_invested_amount [integer]: invested amount withdrawn in this step, in cents. ex: 206700 (= R$ 2,067.00)
    - yield_amount [integer]: yield withdrawn in this step, in cents. ex: 3630 (= R$ 36.30)
    - created [datetime.datetime]: creation datetime for the log. ex: datetime.datetime(2020, 3, 10, 10, 30, 0, 0)
    """

    def __init__(self, id, investment, type, description, errors, taxes, transaction_id, transaction_amount,
                 withdrawn_invested_amount, yield_amount, created):
        Resource.__init__(self, id=id)

        self.investment = from_api_json(_fixed_investment_resource, investment)
        self.type = type
        self.description = description
        self.errors = errors
        self.taxes = taxes
        self.transaction_id = transaction_id
        self.transaction_amount = transaction_amount
        self.withdrawn_invested_amount = withdrawn_invested_amount
        self.yield_amount = yield_amount
        self.created = check_datetime(created)


_resource = {"class": Log, "name": "FixedInvestmentLog"}


def get(id, user=None):
    """# Retrieve a specific fixedinvestment.Log
    Receive a single fixedinvestment.Log object previously created by the Stark Bank API by its id
    ## Parameters (required):
    - id [string]: object unique id. ex: "5656565656565656"
    ## Parameters (optional):
    - user [Organization/Project object, default None]: Organization or Project object. Not necessary if starkbank.user was set before function call
    ## Return:
    - fixedinvestment.Log object with updated attributes
    """
    return rest.get_id(resource=_resource, id=id, user=user)


def query(limit=None, after=None, before=None, investment_ids=None, user=None):
    """# Retrieve fixedinvestment.Logs
    Receive a generator of fixedinvestment.Log objects previously created in the Stark Bank API
    ## Parameters (optional):
    - limit [integer, default None]: maximum number of objects to be retrieved. Unlimited if None. ex: 35
    - after [datetime.date or string, default None]: date filter for objects created only after specified date. ex: datetime.date(2020, 3, 10)
    - before [datetime.date or string, default None]: date filter for objects created only before specified date. ex: datetime.date(2020, 3, 10)
    - investment_ids [list of strings, default None]: list of FixedInvestment ids to filter logs. ex: ["5656565656565656", "4545454545454545"]
    - user [Organization/Project object, default None]: Organization or Project object. Not necessary if starkbank.user was set before function call
    ## Return:
    - generator of fixedinvestment.Log objects with updated attributes
    """
    return rest.get_stream(
        resource=_resource,
        limit=limit,
        after=check_date(after),
        before=check_date(before),
        investment_ids=investment_ids,
        user=user,
    )


def page(cursor=None, limit=None, after=None, before=None, investment_ids=None, user=None):
    """# Retrieve paged fixedinvestment.Logs
    Receive a list of up to 100 fixedinvestment.Log objects previously created in the Stark Bank API and the cursor to the next page.
    Use this function instead of query if you want to manually page your requests.
    ## Parameters (optional):
    - cursor [string, default None]: cursor returned on the previous page function call
    - limit [integer, default 100]: maximum number of objects to be retrieved. It must be an integer between 1 and 100. ex: 50
    - after [datetime.date or string, default None]: date filter for objects created only after specified date. ex: datetime.date(2020, 3, 10)
    - before [datetime.date or string, default None]: date filter for objects created only before specified date. ex: datetime.date(2020, 3, 10)
    - investment_ids [list of strings, default None]: list of FixedInvestment ids to filter logs. ex: ["5656565656565656", "4545454545454545"]
    - user [Organization/Project object, default None]: Organization or Project object. Not necessary if starkbank.user was set before function call
    ## Return:
    - list of fixedinvestment.Log objects with updated attributes
    - cursor to retrieve the next page of fixedinvestment.Log objects
    """
    return rest.get_page(
        resource=_resource,
        cursor=cursor,
        limit=limit,
        after=check_date(after),
        before=check_date(before),
        investment_ids=investment_ids,
        user=user,
    )
